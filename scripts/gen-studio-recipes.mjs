/**
 * Generates server/src/modules/smrtstudio/recipes.ts from video-lab's
 * docs/models/*.md.
 *
 * Only per-model recipes are included. The memos, the research index and the
 * pronunciation playbook are research documents about many models at once, not
 * one model's how-to, so they are skipped and stay in the research centre.
 *
 * Usage: node scripts/gen-studio-recipes.mjs [path-to-video-lab]
 */
import fs from "node:fs";
import path from "node:path";

const LAB = process.argv[2] ?? "/home/user/video-lab";
const SRC = path.join(LAB, "docs/models");
const SKIP = new Set([
  "README.md",
  "prices-memo.md",
  "voice-memo.md",
  "sub-research-2b.md",
  "havara-playbook.md",
]);

const files = fs.readdirSync(SRC).filter((f) => f.endsWith(".md") && !SKIP.has(f));
const out = {};
const skipped = [];

for (const f of files) {
  const raw = fs.readFileSync(path.join(SRC, f), "utf8");
  const h1 = raw.match(/^#\s+(.+)$/m);
  // The endpoint id is the join key to studio_models. It is the first
  // backticked owner/path token, which the H1 always carries.
  const idm = raw.match(/`([a-z0-9-]+\/[A-Za-z0-9._/-]+)`/);
  if (!idm) {
    skipped.push(f);
    continue;
  }
  const endpoint = idm[1];
  const title = (h1 ? h1[1] : f).replace(/\s*\(`[^`]+`\)\s*$/, "").trim();
  const note = (raw.match(/^>\s+(.+(?:\n>\s+.+)*)/m) ?? ["", ""])[1]
    .replace(/\n>\s+/g, " ")
    .trim();

  // Split on the H2 boundaries rather than matching each block: a regex with a
  // trailing lookahead silently drops the LAST section, which cost us the
  // "links" section on the first pass.
  const parts = raw.split(/^##\s+/m).slice(1);
  const sections = parts.map((p) => {
    const nl = p.indexOf("\n");
    return {
      heading: (nl === -1 ? p : p.slice(0, nl)).trim(),
      body: (nl === -1 ? "" : p.slice(nl + 1)).trim(),
    };
  });
  out[endpoint] = { file: "docs/models/" + f, title, note, sections };
}

const header = `/**
 * Per-model recipes — the written method for each model, generated from
 * video-lab's docs/models/*.md so the server can serve it without reaching into
 * another repo at request time.
 *
 * This is the HOW: when to use the model, the recommended feeding method
 * (official plus community), prompt structure, tricks and limits. It is prose a
 * human wrote and it changes only when a human changes it.
 *
 * A model's INPUT FIELDS are deliberately NOT stored here — they are read live
 * from fal's OpenAPI schema on every request, because a stored copy of a
 * contract is a contract that can silently go stale. Written method here, live
 * contract there.
 *
 * Generated by scripts/gen-studio-recipes.mjs — do not edit by hand.
 */

export type RecipeSection = { heading: string; body: string };

export type ModelRecipe = {
  /** repo-relative path in video-lab, so a reader can open the original */
  file: string;
  title: string;
  /** the provenance line: when it was verified and against what */
  note: string;
  sections: RecipeSection[];
};

export const MODEL_RECIPES: Record<string, ModelRecipe> = `;

fs.writeFileSync(
  "server/src/modules/smrtstudio/recipes.ts",
  header + JSON.stringify(out, null, 2) + ";\n",
);
console.log(`recipes: ${Object.keys(out).length}`);
if (skipped.length) console.log(`skipped (no endpoint id): ${skipped.join(", ")}`);
